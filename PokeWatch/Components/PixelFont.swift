    static func glyph(_ c: Character) -> [String] {
        glyphs[c] ?? glyphs[Character(c.uppercased())] ?? glyphs["?"]!
    }

    /// Width in font pixels including 1-pixel letter spacing (minus trailing space).
    static func width(of text: String) -> Int {
        let w = text.reduce(0) { $0 + glyph($1)[0].count + 1 }
        return max(0, w - 1)
    }

    static func path(for text: String, pixel: CGFloat) -> Path {
        var path = Path()
        var x = 0
        for ch in text {
            let g = glyph(ch)
            for (row, line) in g.enumerated() {
                for (col, cell) in line.enumerated() where cell == "#" {
                    path.addRect(CGRect(x: CGFloat(x + col) * pixel, y: CGFloat(row) * pixel, width: pixel, height: pixel))
                }
            }
            x += g[0].count + 1
        }
        return path
    }
}

/// Text drawn with `PixelFont`, sized exactly to its pixels.
struct PixelText: View {
    let text: String
    var pixel: CGFloat = 2
    var color: Color = Palette.ink

    var body: some View {
        let t = text.uppercased()
        PixelPathShape(text: t, pixel: pixel)
            .fill(color)
            .frame(width: CGFloat(PixelFont.width(of: t)) * pixel, height: CGFloat(PixelFont.height) * pixel)
            .accessibilityLabel(text)
    }
}

private struct PixelPathShape: Shape {
    let text: String
    let pixel: CGFloat
    func path(in rect: CGRect) -> Path { PixelFont.path(for: text, pixel: pixel) }
}
